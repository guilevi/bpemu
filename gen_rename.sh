#!/bin/sh
# gen_rename.sh OBJ... > rename.h
#
# Every external symbol the M16C core defines or uses (other than libc's),
# renamed with a bp_ prefix.  Compiling the Book Port's copy of the core under
# this header lets it share the process with the RC8650's copy, which keeps
# the original names.
set -e
{
  nm -g "$@" | awk 'NF >= 2 { print $NF }' | sed 's/^_//'
  # mem.h's interface: bp_hw.c implements these instead of mem.c.
  for s in mem_get_qi mem_get_hi mem_get_psi mem_get_si mem_put_qi mem_put_hi \
           mem_put_psi mem_put_si mem_get_pc mem_put_blk mem_get_blk init_mem \
           mem_usage_stats sign_ext decode_opcode decode_m32c \
           m32c_sim_restore_console m32c_use_raw_console; do
    echo $s
  done
} | grep -v -E '^_' \
  | grep -v -x -E 'abort|exit|memset|memcpy|memmove|strcmp|strlen|puts|putchar|printf|fprintf|vfprintf|fflush|fputs|fputc|fwrite|malloc|calloc|free|sprintf|snprintf|bzero|abs|stderr|stdout|stack_chk_fail|stack_chk_guard|dyld_stub_binder|lround|sin|cos' \
  | sort -u \
  | {
      echo '/* Generated by gen_rename.sh: gives the Book Port copy of the M16C core'
      echo '   its own symbol names, so it can share a process with the RC8650 copy. */'
      echo '#ifndef BP_RENAME_H'
      echo '#define BP_RENAME_H'
      while read s; do echo "#define $s bp_$s"; done
      echo '#endif'
    }
